import streamlit as st
from modules.input_helpers import close_sidebar_on_mobile
import sys
import os
from modules.page_utils import switch_page
from modules.auth import require_login

# モジュールのインポートパスを追加
sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

def run():
    require_login()

    # スマホでサイドバーを自動的に閉じる
    close_sidebar_on_mobile()
    
    # タイトルとホームボタンを横に配置
    col1, col2 = st.columns([0.8, 0.2])
    with col1:
        st.title("マニュアル")
    with col2:
        if st.button("🏠 Home", key="manual_home_button"):
            st.switch_page("main.py")
    
    # マニュアルの内容を表示
    display_embedded_manual()

def display_embedded_manual():
    """
    埋め込みマニュアルを表示
    """
    st.markdown("""
# Golf Score App マニュアル

## 1. このアプリでできること

ラウンドの設定、参加者・ハンディキャップの登録、OUT／IN／エキストラのスコア・パット・ゲームポイント入力、結果確認、PDF出力、ポイント集計を行えます。通常の入力に加え、Golf Network のスコアカード画像から各区分の合計値を候補として読み取れます。

## 2. 基本的な使い方

### 2.1 メンバー登録

1. メインメニューから「メンバー登録」を開きます。
2. メンバー名を入力して登録します。

### 2.2 ラウンド設定

1. 「ラウンド設定」を開き、日付・ゴルフ場・参加メンバー・ハンディキャップを設定します。
2. 内容を保存します。

### 2.3 スコア入力

通常は次の順に入力します。

1. 「フロントスコア入力」で OUT（1〜9番）を入力します。
2. 「バックスコア入力」で IN（10〜18番）を入力します。
3. 追加の9ホールを実施した場合のみ、「エキストラスコア入力」でエキストラ（19〜27番）を入力します。
4. 「結果確認」で内容を確認し、必要に応じてPDFを出力してラウンドを確定します。

ゲームポイントはスコア・パットとは別の入力項目です。画像から反映した後も、保存前に各値を確認してください。

## 3. スコアカード画像の読み取り

### 対応する画面と対象ホール

各スコア入力画面の「📷 画像からスコアを読み取る」を開いて使用します。

| 画面 | 読み取る区分 |
| --- | --- |
| フロントスコア入力 | OUT（1〜9番）の合計スコア・パット・ゲームポイント |
| バックスコア入力 | IN（10〜18番）の合計スコア・パット・ゲームポイント |
| エキストラスコア入力 | エキストラ（19〜27番）の合計スコア・パット・ゲームポイント |

Golf Network のスコア表を主な対象としています。スコア表全体、参加者名、対象区分の合計欄が1枚に収まった画像を選んでください。縦長のスクリーンショットは、読み取り前に自動で横向きへ補正されます。

### 読み取り手順

1. 対象のスコア入力画面を開きます。
2. 「📷 画像から…を読み取る」を開きます。
3. 「スコアカード画像を選択」から画像ファイルを選択します。対応形式は JPG／JPEG／PNG／WEBP です。
4. 「画像を読み取る」を押します。
5. 表示された候補（プレイヤー、スコア、パット、ゲームポイント）を元のスコア表と照合します。
6. 問題がなければ「候補を入力欄へ反映」を押し、通常どおり保存します。

この機能はカメラ撮影機能ではありません。端末に保存済みの画像ファイルを選択して利用します。

### 読み取り結果について

- 参加者名は、現在のラウンドに登録されているメンバー名と照合して反映します。画像内の表記が異なる、または判別できない参加者は候補に含まれません。
- 色付きのプレイヤー行から打数とパット数を読み取り、対象9ホールの合計欄と照合します。
- ゲームポイントはプレイヤー行の直下にある細い数値行の、対象9ホール最後の合計値を読み取ります。
- 結果は自動保存されません。「候補を入力欄へ反映」後に、画面の保存操作を行うまでラウンドデータは更新されません。
- AIによる読み取りは候補の作成を支援する機能です。確定値ではないため、必ず元画像と照合してください。

### うまく読み取れない場合

- 画像をトリミングせず、表全体・氏名・合計欄が見える元画像を使用してください。
- 文字や数値が小さい場合は、高解像度のスクリーンショットを選択してください。
- 画面の反射、ぼけ、強い傾き、隠れた列がある画像では精度が下がります。
- 一部の参加者だけ候補に出ない、または値に疑いがある場合は、その項目を手入力で修正してください。
- 「OPENAI_API_KEY を設定してください」と表示される場合は、運用者がRailwayの環境変数 `OPENAI_API_KEY` を設定する必要があります。
- 画像読取りにはインターネット接続とOpenAI APIの利用可能なクレジットが必要です。オフライン入力中は利用できません。

## 4. 電波が弱い場所での入力

1. 出発前にラウンド設定を保存します。
2. 「オフライン入力」で未確定ラウンドを選び、開始ファイル（JSON）を端末へ保存します。
3. 現地で開始ファイルを読み込み、OUT・IN・エキストラを手入力します。入力内容は端末内に保存されます。
4. ラウンド後に同期ファイル（`-sync.json`）を保存します。
5. 通信復帰後、「オフライン入力」で同期ファイルを選び、同期して結果を更新します。

画像読取りはOpenAI APIへの通信が必要なため、オフライン入力では使用できません。

## 5. 注意事項

- ラウンドデータはSupabaseに保存されます。
- 読取りに使う画像には参加者名とスコアが含まれます。利用時はOpenAI APIへ画像が送信されます。
- APIキーやパスワードは画面・画像・ソースコードに貼り付けず、Railwayなどの環境変数で管理してください。
""")

if __name__ == "__main__":
    run()
else:
    # Streamlit Pages用の直接実行
    run()
